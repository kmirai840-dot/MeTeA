def build_user_prompt(
    matching_context: dict[str, Any],
) -> str:
    """AIへ渡す評価対象データをJSON文字列にする。"""

    if not isinstance(
        matching_context,
        dict,
    ):
        raise TypeError(
            "AI入力情報は辞書である必要があります"
        )

    if not matching_context:
        raise ValueError(
            "AI入力情報が空です"
        )

    context_json = json.dumps(
        matching_context,
        ensure_ascii=False,
        indent=2,
        default=str,
    )

    return (
        "以下の利用者情報と求人情報を比較し、"
        "指定されたJSON形式で項目別判定を返してください。\n\n"
        "評価対象データ:\n"
        f"{context_json}"
    )


def build_ai_matching_messages(
    matching_context: dict[str, Any],
) -> list[dict[str, str]]:
    """AIへ送るsystem・userメッセージを作成する。"""

    return [
        {
            "role": "system",
            "content": SYSTEM_PROMPT,
        },
        {
            "role": "user",
            "content": build_user_prompt(
                matching_context
            ),
        },
    ]
